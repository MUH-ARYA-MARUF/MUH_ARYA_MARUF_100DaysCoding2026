public class Main {
    public static void main(String[] args) {

        int angka = 100;

        // Konversi otomatis dari int ke long
        long angkaLong = angka;

        // Konversi otomatis dari long ke float
        float angkaFloat = angkaLong;

        // Konversi otomatis dari float ke double
        double angkaDouble = angkaFloat;

        System.out.println("Nilai int    : " + angka);
        System.out.println("Nilai long   : " + angkaLong);
        System.out.println("Nilai float  : " + angkaFloat);
        System.out.println("Nilai double : " + angkaDouble);
    }
}
